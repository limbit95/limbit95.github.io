create or replace function public.join_event(p_event_id bigint)
returns text
language plpgsql
security definer
set search_path = ''
as $$
declare
    v_user_id uuid := auth.uid();
    v_event public.events%rowtype;
    v_existing_status text;
    v_joined_count integer;
    v_new_status text;
    v_actor_name text;
begin
    if v_user_id is null or not private.is_approved_member() then
        raise exception '승인된 회원만 활동에 참여할 수 있습니다.' using errcode = '42501';
    end if;

    select e.* into v_event from public.events as e
    where e.id = p_event_id for update;
    if not found then
        raise exception '활동을 찾을 수 없습니다.' using errcode = 'P0002';
    end if;
    if v_event.status <> 'scheduled' then
        raise exception '현재 참여 신청을 받을 수 없는 활동입니다.' using errcode = '23514';
    end if;
    if now() > v_event.registration_deadline then
        raise exception '참여 신청이 마감되었습니다.' using errcode = '23514';
    end if;

    select ep.status into v_existing_status
    from public.event_participants as ep
    where ep.event_id = p_event_id and ep.user_id = v_user_id for update;
    if found and v_existing_status in ('joined', 'waitlisted') then
        raise exception '이미 참여 또는 대기 신청한 활동입니다.' using errcode = '23505';
    end if;

    select count(*)::integer into v_joined_count
    from public.event_participants as ep
    where ep.event_id = p_event_id and ep.status = 'joined';
    v_new_status := case
        when v_event.capacity is null or v_joined_count < v_event.capacity then 'joined'
        else 'waitlisted'
    end;

    insert into public.event_participants (
        event_id, user_id, status, joined_at, waitlisted_at, cancelled_at
    ) values (
        p_event_id, v_user_id, v_new_status,
        case when v_new_status = 'joined' then now() else null end,
        case when v_new_status = 'waitlisted' then now() else null end,
        null
    )
    on conflict (event_id, user_id) do update
    set status = excluded.status,
        joined_at = excluded.joined_at,
        waitlisted_at = excluded.waitlisted_at,
        cancelled_at = null;

    if v_event.organizer_id <> v_user_id then
        select coalesce(nullif(btrim(p.display_name), ''), '회원') into v_actor_name
        from public.profiles as p where p.id = v_user_id;
        insert into public.notifications (
            user_id, notification_type, kind, title, body, event_id, target_path
        ) values (
            v_event.organizer_id,
            case when v_new_status = 'joined' then 'event_participant_joined' else 'event_participant_waitlisted' end,
            case when v_new_status = 'joined' then 'event_participant_joined' else 'event_participant_waitlisted' end,
            case when v_new_status = 'joined' then '새로운 활동 참여' else '새로운 대기 신청' end,
            case when v_new_status = 'joined'
                then format('%s님이 ''%s'' 활동에 참여했습니다.', v_actor_name, v_event.title)
                else format('%s님이 ''%s'' 활동에 대기 신청했습니다.', v_actor_name, v_event.title)
            end,
            p_event_id,
            format('#/activities/%s', p_event_id)
        );
    end if;
    return v_new_status;
end;
$$;

create or replace function public.cancel_event_participation(p_event_id bigint)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
    v_user_id uuid := auth.uid();
    v_event public.events%rowtype;
    v_current_status text;
    v_promoted_user_id uuid;
    v_joined_count integer;
    v_actor_name text;
begin
    if v_user_id is null or not private.is_approved_member() then
        raise exception '승인된 회원만 참여를 취소할 수 있습니다.' using errcode = '42501';
    end if;

    select e.* into v_event
    from public.events as e
    where e.id = p_event_id
    for update;

    if not found then
        raise exception '활동을 찾을 수 없습니다.' using errcode = 'P0002';
    end if;

    if v_event.status not in ('scheduled', 'closed') then
        raise exception '현재 참여 취소를 처리할 수 없는 활동입니다.' using errcode = '23514';
    end if;

    if now() > v_event.registration_deadline then
        raise exception '참여 취소 가능 시간이 지났습니다.' using errcode = '23514';
    end if;

    select ep.status into v_current_status
    from public.event_participants as ep
    where ep.event_id = p_event_id
      and ep.user_id = v_user_id
    for update;

    if not found or v_current_status = 'cancelled' then
        raise exception '취소할 참여 정보가 없습니다.' using errcode = 'P0002';
    end if;

    if v_event.series_id is null
       and v_event.organizer_id = v_user_id
       and v_current_status = 'joined'
       and exists (
           select 1
           from public.event_participants as other_participant
           where other_participant.event_id = p_event_id
             and other_participant.user_id <> v_user_id
             and other_participant.status = 'joined'
       ) then
        raise exception '다른 참여자가 있는 활동의 주최자는 먼저 주최자를 변경해야 합니다.'
            using errcode = '23514';
    end if;

    update public.event_participants
    set status = 'cancelled', cancelled_at = now()
    where event_id = p_event_id
      and user_id = v_user_id;

    if v_event.organizer_id <> v_user_id then
        select coalesce(nullif(btrim(p.display_name), ''), '회원') into v_actor_name
        from public.profiles as p
        where p.id = v_user_id;

        insert into public.notifications (
            user_id, notification_type, kind, title, body, event_id, target_path
        ) values (
            v_event.organizer_id,
            'event_participation_cancelled',
            'event_participation_cancelled',
            '활동 참여 취소',
            format('%s님이 ''%s'' 활동 참여를 취소했습니다.', v_actor_name, v_event.title),
            p_event_id,
            format('#/activities/%s', p_event_id)
        );
    end if;

    if v_current_status = 'joined' then
        select count(*)::integer into v_joined_count
        from public.event_participants as ep
        where ep.event_id = p_event_id
          and ep.status = 'joined';

        if v_event.capacity is null or v_joined_count < v_event.capacity then
            select ep.user_id into v_promoted_user_id
            from public.event_participants as ep
            where ep.event_id = p_event_id
              and ep.status = 'waitlisted'
            order by ep.waitlisted_at asc, ep.created_at asc
            for update skip locked
            limit 1;

            if v_promoted_user_id is not null then
                update public.event_participants
                set status = 'joined',
                    joined_at = now(),
                    waitlisted_at = null,
                    cancelled_at = null
                where event_id = p_event_id
                  and user_id = v_promoted_user_id;

                insert into public.notifications (
                    user_id, notification_type, title, body, event_id
                ) values (
                    v_promoted_user_id,
                    'waitlist_promoted',
                    '활동 참여가 확정되었어요',
                    format('대기 중이던 "%s" 활동에 참여할 수 있게 되었습니다.', v_event.title),
                    p_event_id
                );
            end if;
        end if;
    end if;
end;
$$;

create or replace function public.remove_or_cancel_event(p_event_id bigint)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_event public.events%rowtype;
  v_user_id uuid := auth.uid();
begin
  if v_user_id is null or not private.is_approved_member() then
    raise exception '승인된 회원만 활동을 관리할 수 있습니다.' using errcode = '42501';
  end if;

  select * into v_event
  from public.events
  where id = p_event_id
  for update;

  if not found then
    raise exception '활동을 찾을 수 없습니다.' using errcode = 'P0002';
  end if;

  if not (
    private.has_admin_permission('community')
    or private.is_category_manager(v_event.category_id)
    or (
      v_event.series_id is null
      and v_event.organizer_id = v_user_id
      and v_event.status in ('scheduled', 'closed')
    )
  ) then
    raise exception '이 활동을 삭제할 권한이 없습니다.' using errcode = '42501';
  end if;

  if v_event.series_id is not null or exists (
    select 1 from public.event_participants participant
    where participant.event_id = p_event_id
      and participant.user_id <> v_event.organizer_id
  ) or exists (
    select 1 from public.notifications notification
    where notification.event_id = p_event_id
      and notification.notification_type <> 'new_activity'
  ) or exists (
    select 1 from public.date_polls poll
    where poll.result_event_id = p_event_id
  ) then
    if v_event.status <> 'cancelled' then
      update public.events set status = 'cancelled' where id = p_event_id;
    end if;
    return jsonb_build_object('action', 'cancelled', 'event_id', p_event_id);
  end if;

  delete from public.events where id = p_event_id;
  return jsonb_build_object('action', 'deleted', 'event_id', p_event_id);
end;
$$;

create or replace function public.transfer_event_organizer(
    p_event_id bigint,
    p_new_organizer_id uuid,
    p_leave_current boolean default false
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
    v_user_id uuid := auth.uid();
    v_event public.events%rowtype;
    v_new_organizer_status text;
begin
    if v_user_id is null or not private.is_approved_member() then
        raise exception '승인된 회원만 주최자를 변경할 수 있습니다.' using errcode = '42501';
    end if;

    select e.* into v_event
    from public.events as e
    where e.id = p_event_id
    for update;

    if not found then
        raise exception '활동을 찾을 수 없습니다.' using errcode = 'P0002';
    end if;

    if v_event.series_id is not null then
        raise exception '반복 활동 일정의 주최자는 개별 변경할 수 없습니다.' using errcode = '23514';
    end if;

    if v_event.status not in ('scheduled', 'closed') then
        raise exception '현재 상태에서는 주최자를 변경할 수 없습니다.' using errcode = '23514';
    end if;

    if v_event.organizer_id <> v_user_id then
        raise exception '현재 주최자만 주최자를 변경할 수 있습니다.' using errcode = '42501';
    end if;

    if p_new_organizer_id is null or p_new_organizer_id = v_user_id then
        raise exception '다른 참여자를 새 주최자로 선택해주세요.' using errcode = '23514';
    end if;

    select ep.status into v_new_organizer_status
    from public.event_participants as ep
    where ep.event_id = p_event_id
      and ep.user_id = p_new_organizer_id
    for update;

    if not found or v_new_organizer_status <> 'joined' then
        raise exception '현재 참여 중인 회원에게만 주최자를 넘길 수 있습니다.' using errcode = '23514';
    end if;

    perform set_config('app.allow_event_organizer_transfer', 'true', true);
    perform set_config(
      'app.event_organizer_previous_leaves',
      case when p_leave_current then 'true' else 'false' end,
      true
    );

    update public.events
    set organizer_id = p_new_organizer_id
    where id = p_event_id;

    perform set_config('app.allow_event_organizer_transfer', 'false', true);
    perform set_config('app.event_organizer_previous_leaves', 'false', true);

    if p_leave_current then
        perform public.cancel_event_participation(p_event_id);
    end if;

    return jsonb_build_object(
        'event_id', p_event_id,
        'creator_id', v_event.created_by,
        'previous_organizer_id', v_user_id,
        'organizer_id', p_new_organizer_id,
        'left_activity', p_leave_current
    );
end;
